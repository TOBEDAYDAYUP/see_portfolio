import type {StockRiskSummary,ResearchArticle} from "../research/types";
import type {AssistantTechnicalIndicators} from "./technical-indicators";

export type StockAnalysisFundamentals={
 fiscalYearEnd:string;
 annualRevenueUSD:number|null;
 annualNetIncomeUSD:number|null;
 annualDilutedEPSUSD:number|null;
 ttmPeriodEnd:string|null;
 ttmPEApprox:number|null;
 ttmPSProxy:number|null;
 latestPBProxy:number|null;
 ttmFCFYieldPct:number|null;
};
export type StockAnalysisInput={
 symbol:string;
 asOf:string|null;
 lastCloseUSD:number|null;
 previousCloseUSD:number|null;
 technicals:AssistantTechnicalIndicators;
 risk:StockRiskSummary|null;
 fundamentals:StockAnalysisFundamentals|null;
 headlines:ReadonlyArray<Pick<ResearchArticle,"headline"|"source"|"publishedAt">>;
 sources:{price?:string;fundamentals?:string;news?:string};
 notes:readonly string[];
};
const valid=(n:number|null|undefined):n is number=>typeof n==="number"&&Number.isFinite(n);
const value=(n:number|null|undefined,digits=2)=>valid(n)?n.toFixed(digits):"—";
const pct=(n:number|null|undefined)=>valid(n)?(n>0?"+":"")+n.toFixed(2)+"%":"—";
const currency=(n:number|null|undefined)=>valid(n)?"USD "+n.toFixed(2):"—";
const billion=(n:number|null|undefined)=>valid(n)?"USD "+(n/1e9).toFixed(2)+"B":"—";
const ref=(id?:string)=>id?" ["+id+"]":"";
const maAlignment=(t:AssistantTechnicalIndicators)=>{
 const {sma5:a,sma10:b,sma20:c}=t;
 if(!valid(a)||!valid(b)||!valid(c))return "unavailable" as const;
 return a>b&&b>c?"upward" as const:a<b&&b<c?"downward" as const:"mixed" as const;
};

/** Analysis-intent classifier: casual chat and isolated financial questions
 * still pass through Ollama/DeepSeek as ordinary conversations. */
export function requestsStandardStockReport(query:string,symbols:readonly string[],portfolio=false):boolean{
 if(portfolio||symbols.length!==1)return false;
 return /\b(analy[sz]e|analysis|research report|stock report|equity report|technical analysis|fundamental analysis|full report|company overview|stock overview|investment thesis)\b|分析|研究报告|股票报告|个股报告|股票研报|全面评估|技术面|基本面分析|估值分析/i.test(query);
}

/** Evidence-only, fixed-schema report. Numeric claims are NEVER generated by
 * the language model, and all missing metrics are visibly withheld. */
export function formatStandardStockReport(data:StockAnalysisInput,language:"en"|"zh"="en"):string{
 const zh=language==="zh";
 const t=data.technicals,r=data.risk,f=data.fundamentals;
 const priceRef=ref(data.sources.price),finRef=ref(data.sources.fundamentals),newsRef=ref(data.sources.news);
 const movement=valid(data.lastCloseUSD)&&valid(data.previousCloseUSD)&&data.previousCloseUSD>0
  ?(data.lastCloseUSD/data.previousCloseUSD-1)*100:null;
 const alignment=maAlignment(t);
 const momentum=valid(t.macdHistogram)?t.macdHistogram>0?"positive":t.macdHistogram<0?"negative":"neutral":"unavailable";
 const summary=zh?[
   alignment==="upward"?"均线呈上行排列。":alignment==="downward"?"均线呈下行排列。":alignment==="mixed"?"均线排列混合。":"均线数据不足。",
   momentum==="positive"?"MACD 柱值为正。":momentum==="negative"?"MACD 柱值为负。":momentum==="neutral"?"MACD 柱值接近零。":"MACD 信号不可用。",
   valid(r?.expectedShortfall95Pct)?"历史 1 日 ES95 为 "+value(r?.expectedShortfall95Pct)+"%，仅代表样本内尾部损失。":"历史 ES95 数据不足。",
   "这是历史数据描述，并非未来价格预测或交易指令。"
  ].join(" "):[
   alignment==="upward"?"Short moving averages are aligned upward.":alignment==="downward"?"Short moving averages are aligned downward.":alignment==="mixed"?"Moving-average alignment is mixed.":"There is insufficient moving-average history.",
   momentum==="positive"?"The MACD histogram is positive.":momentum==="negative"?"The MACD histogram is negative.":momentum==="neutral"?"The MACD histogram is near zero.":"The MACD signal is unavailable.",
   valid(r?.expectedShortfall95Pct)?"Historical 1-day ES95 is "+value(r?.expectedShortfall95Pct)+"%, an in-sample tail-loss estimate.":"Historical ES95 is unavailable.",
   "These are historical observations, not a price forecast or trade instruction."
  ].join(" ");

 const sections=zh?[
  ["市场概览",[
    "最近完成的 IEX 日收盘价："+currency(data.lastCloseUSD)+"；交易日："+(data.asOf??"—"),
    "相对上个交易日："+pct(movement)+"；上次收盘价："+currency(data.previousCloseUSD)+priceRef,
    "行情类型：Alpaca IEX 历史日线，不是全市场实时成交价。"]],
  ["趋势与指标",[
    "SMA5："+currency(t.sma5)+"；SMA10："+currency(t.sma10)+"；SMA20："+currency(t.sma20),
    "5 个交易日收益率："+pct(t.return5Pct)+"；20 个交易日收益率："+pct(t.return20Pct),
    "均线状态："+(alignment==="upward"?"上行排列":alignment==="downward"?"下行排列":alignment==="mixed"?"混合":"数据不足")+priceRef]],
  ["RSI 与 MACD 动量",[
    "RSI(14, Wilder)："+value(t.rsi14)+"；超买/超卖参考区间为 70 / 30，不能单独作交易信号。",
    "MACD(12,26,9)："+value(t.macdLine,3)+"；Signal："+value(t.macdSignal,3)+"；Histogram："+value(t.macdHistogram,3)+priceRef]],
  ["波动与风险",[
    "年化历史波动率："+pct(r?.annualizedVolatilityPct)+"；最大回撤："+pct(r?.maxDrawdownPct),
    "1 日历史 VaR95："+pct(r?.var95Pct)+"；1 日历史 ES95："+pct(r?.expectedShortfall95Pct),
    "有效日收益样本："+(r?.observations??0)+"；VaR/ES 最低需要 200 条。所有结果仅为样本内历史估计。"+priceRef]],
  ["基本面与估值",[
    "财年末："+(f?.fiscalYearEnd??"—")+"；营收："+billion(f?.annualRevenueUSD)+"；净利润："+billion(f?.annualNetIncomeUSD)+"；摊薄 EPS："+currency(f?.annualDilutedEPSUSD),
    "TTM 截止："+(f?.ttmPeriodEnd??"—")+"；近似 TTM P/E："+value(f?.ttmPEApprox)+"×；P/S（股数代理）："+value(f?.ttmPSProxy)+"×；P/B（股数代理）："+value(f?.latestPBProxy)+"×；FCF Yield（代理）："+pct(f?.ttmFCFYieldPct),
    "倍数不等于内在价值，股数快照可能滞后。"+finRef]],
  ["成交量与新闻",[
    "交易量：当前分析仅使用核实过的日收盘价，没有完整 OHLCV 成交量输入，因此不提供成交量比值。",
    data.headlines.length?data.headlines.slice(0,3).map(h=>h.headline+"（"+h.source+"；"+h.publishedAt+"）").join("；")+newsRef:"新闻：仅在明确提出新闻问题时检索；未核实则不做新闻结论。"]],
  ["Summary｜证据摘要",[summary]],
 ]:[
  ["Market Snapshot",[
    "Last completed IEX daily close: "+currency(data.lastCloseUSD)+"; session: "+(data.asOf??"—"),
    "Change vs prior session: "+pct(movement)+"; prior close: "+currency(data.previousCloseUSD)+priceRef,
    "Quote scope: Historical Alpaca IEX daily close, NOT a live consolidated quote."]],
  ["Trend & Indicators",[
    "SMA5: "+currency(t.sma5)+"; SMA10: "+currency(t.sma10)+"; SMA20: "+currency(t.sma20),
    "5-session return: "+pct(t.return5Pct)+"; 20-session return: "+pct(t.return20Pct),
    "MA alignment: "+alignment+priceRef]],
  ["Momentum: RSI & MACD",[
    "RSI(14, Wilder): "+value(t.rsi14)+"; 30/70 are conventional reference levels, not stand-alone trading signals.",
    "MACD(12,26,9): "+value(t.macdLine,3)+"; signal: "+value(t.macdSignal,3)+"; histogram: "+value(t.macdHistogram,3)+priceRef]],
  ["Volatility & Tail Risk",[
    "Annualized historical volatility: "+pct(r?.annualizedVolatilityPct)+"; maximum drawdown: "+pct(r?.maxDrawdownPct),
    "1-day historical VaR95: "+pct(r?.var95Pct)+"; 1-day historical ES95: "+pct(r?.expectedShortfall95Pct),
    "Valid daily return observations: "+(r?.observations??0)+"; VaR/ES require at least 200. All estimates are in-sample."+priceRef]],
  ["Fundamentals & Valuation",[
    "Fiscal year ended: "+(f?.fiscalYearEnd??"—")+"; revenue: "+billion(f?.annualRevenueUSD)+"; net income: "+billion(f?.annualNetIncomeUSD)+"; diluted EPS: "+currency(f?.annualDilutedEPSUSD),
    "TTM period ended: "+(f?.ttmPeriodEnd??"—")+"; approx. TTM P/E: "+value(f?.ttmPEApprox)+"×; P/S share proxy: "+value(f?.ttmPSProxy)+"×; P/B share proxy: "+value(f?.latestPBProxy)+"×; FCF yield proxy: "+pct(f?.ttmFCFYieldPct),
    "Multiples are not intrinsic value; SEC share counts can be dated."+finRef]],
  ["Volume & News",[
    "Volume: not available in this verified daily-CLOSE feed; no volume ratio is inferred.",
    data.headlines.length?data.headlines.slice(0,3).map(h=>h.headline+" ("+h.source+"; "+h.publishedAt+")").join("; ")+newsRef:"News: fetched only when explicitly requested; no unsourced news claim."]],
  ["Summary",[summary]],
 ];
 return (zh?"SEE Portfolio 量化个股报告｜":"SEE Portfolio Quantitative Stock Brief | ")+data.symbol+"\n"+
  (zh?"数据截至：":"Data as of: ")+(data.asOf??(zh?"未知":"unavailable"))+"\n\n"+
  sections.map(([heading,lines],i)=>(i+1)+". "+heading+"\n"+
   (lines as string[]).map(line=>"• "+line).join("\n")).join("\n\n")+
  (data.notes.length?"\n\n"+(zh?"数据局限":"Data limitations")+": "+
   data.notes.slice(0,3).join("; "):"")+
  "\n\n"+(zh?"来源编号 [S#] 与数据可在下方 Verified data & sources 展开核对。":"Inspect the matching [S#] sources and dated calculation records under Verified data & sources.");
}
